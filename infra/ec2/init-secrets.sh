#!/usr/bin/env bash
# Operator machine, once: generate the backend's application secrets with a CSPRNG and store them in SSM as
# SecureString under /shriii/prod/. Existing parameters are left untouched (never silently rotated); see
# docs/deploy/aws-ec2.md for rotation. Nothing is printed except parameter names.
#
#   infra/ec2/init-secrets.sh            # needs python3 (or `python`) and the AWS CLI
#
# The database URLs are written by infra/supabase/bootstrap_roles.py, not here.
set -euo pipefail
export MSYS_NO_PATHCONV=1 # Git Bash on Windows: keep /shriii/... paths literal

REGION="${AWS_REGION:-ap-south-1}"
PREFIX=/shriii/prod
PY=""
for candidate in python3 python; do
  if "$candidate" -c 'import secrets' >/dev/null 2>&1; then PY="$candidate" && break; fi
done
[[ -n "$PY" ]] || { echo "init-secrets: python 3 is required" >&2; exit 1; }
TAGS='Key=Project,Value=shriii-kiosk-games Key=Environment,Value=prod'

# name -> generator: b64key32 = base64 of 32 random bytes; passphrase = 32 url-safe characters
declare -A SECRETS=(
  [LOCAL_JWT_SECRET]=b64key48
  [PID_HMAC_PEPPER]=b64key32
  [SESSION_KEY_KEK]=b64key32
  [BACKEND_X25519_PRIVATE_KEY]=b64key32
  [RELEASE_PACK_SIGNING_KEY]=b64key32
  [IDENTITY_VAULT_KEY]=b64key32
  [admin_initial_password]=passphrase
)

gen() {
  case "$1" in
    b64key32) "$PY" -c 'import base64,secrets;print(base64.b64encode(secrets.token_bytes(32)).decode())' ;;
    b64key48) "$PY" -c 'import base64,secrets;print(base64.b64encode(secrets.token_bytes(48)).decode())' ;;
    passphrase) "$PY" -c 'import secrets;print(secrets.token_urlsafe(24))' ;;
  esac
}

for name in "${!SECRETS[@]}"; do
  path="$PREFIX/$name"
  if aws ssm get-parameter --region "$REGION" --name "$path" --query Parameter.Name --output text >/dev/null 2>&1; then
    echo "exists:  $path"
    continue
  fi
  value="$(gen "${SECRETS[$name]}" | tr -d '\r\n')"
  # shellcheck disable=SC2086
  aws ssm put-parameter --region "$REGION" --name "$path" --type SecureString --value "$value" \
    --description "SHRIII backend secret (generated by infra/ec2/init-secrets.sh)" --tags $TAGS >/dev/null
  unset value
  echo "created: $path"
done
